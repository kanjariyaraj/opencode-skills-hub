#!/usr/bin/env python3
"""Run isolated installation smoke tests in Docker.

Safety properties:
  * never touches the host OpenCode config or home directory
  * each case runs in a throwaway container with a temporary mount
  * containers drop all capabilities and enable no-new-privileges
  * cases are pinned to a commit or registry version
  * results are written only after a case finishes

Usage:
  python3 scripts/run_installation_tests.py --list
  python3 scripts/run_installation_tests.py --case theme-catppuccin
  python3 scripts/run_installation_tests.py --all --yes
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CASES_PATH = ROOT / "tests" / "installation" / "cases.json"
RESULTS_JSON = ROOT / "reports" / "installation-results.json"
RESULTS_MD = ROOT / "reports" / "installation-results.md"


def load_cases() -> list[dict]:
    document = json.loads(CASES_PATH.read_text(encoding="utf-8"))
    return document.get("cases", [])


def docker_available() -> bool:
    if not shutil.which("docker"):
        return False
    try:
        result = subprocess.run(
            ["docker", "info"], capture_output=True, text=True, timeout=20
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0


def run_case(case: dict) -> dict:
    started = datetime.now(timezone.utc)
    work = tempfile.mkdtemp(prefix="opencode-install-")
    os.chmod(work, 0o777)
    command = [
        "docker", "run", "--rm",
        "--network", "bridge",
        "--memory", case.get("memory", "2g"),
        "--cpus", "1",
        "--pids-limit", "256",
        "--cap-drop", "ALL",
        "--security-opt", "no-new-privileges",
        "-v", f"{work}:/work",
        "-w", "/work",
        "-e", "HOME=/work/home",
        case["image"],
        "bash", "-lc", "mkdir -p /work/home && " + case["script"],
    ]
    try:
        result = subprocess.run(
            command, capture_output=True, text=True,
            timeout=int(case.get("timeout_seconds", 300)),
        )
        output = (result.stdout or "") + (result.stderr or "")
        exit_code = result.returncode
        status = "PASS" if exit_code == 0 else "FAIL"
    except subprocess.TimeoutExpired as exc:
        output = ""
        if isinstance(exc.stdout, bytes):
            output += exc.stdout.decode("utf-8", "replace")
        elif exc.stdout:
            output += exc.stdout
        if isinstance(exc.stderr, bytes):
            output += exc.stderr.decode("utf-8", "replace")
        elif exc.stderr:
            output += exc.stderr
        exit_code = 124
        status = "TIMEOUT"
    finally:
        subprocess.run(
            ["docker", "run", "--rm", "-v", f"{work}:/work", "alpine:3.20",
             "sh", "-c", "rm -rf /work/* /work/.[!.]* /work/..?*"],
            capture_output=True, text=True, timeout=120,
        )
        shutil.rmtree(work, ignore_errors=True)
    finished = datetime.now(timezone.utc)
    return {
        "id": case["id"],
        "resource_id": case.get("resource_id"),
        "description": case.get("description", ""),
        "image": case["image"],
        "pinned": case.get("pinned"),
        "status": status,
        "exit_code": exit_code,
        "started_at": started.isoformat(),
        "duration_seconds": round((finished - started).total_seconds(), 1),
        "output_tail": output.strip().splitlines()[-40:],
    }


def write_results(results: list[dict]) -> None:
    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "runner": "scripts/run_installation_tests.py",
        "cases": results,
    }
    RESULTS_JSON.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    lines = [
        "# Installation Test Results",
        "",
        "Generated by `scripts/run_installation_tests.py`. These tests run in disposable Docker containers and never touch the host OpenCode configuration.",
        "",
        "| Case | Resource | Status | Pinned | Duration |",
        "| --- | --- | --- | --- | ---: |",
    ]
    for item in results:
        lines.append(
            f"| `{item['id']}` | `{item.get('resource_id') or 'n/a'}` | **{item['status']}** | "
            f"`{item.get('pinned') or 'n/a'}` | {item['duration_seconds']}s |"
        )
    lines.extend(["", "## Output tails", ""])
    for item in results:
        lines.extend([
            f"### `{item['id']}`",
            "",
            f"Status: **{item['status']}** (exit {item['exit_code']})",
            "",
            "```text",
            *item["output_tail"],
            "```",
            "",
        ])
    RESULTS_MD.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Run isolated installation smoke tests.")
    parser.add_argument("--list", action="store_true", help="list cases and exit")
    parser.add_argument("--case", action="append", default=[], help="case id; repeatable")
    parser.add_argument("--all", action="store_true", help="run every case")
    parser.add_argument("--yes", action="store_true", help="confirm Docker execution")
    args = parser.parse_args()

    cases = load_cases()
    if args.list:
        for case in cases:
            print(f"{case['id']:28} {case.get('resource_id', '')}")
        return 0
    selected = cases if args.all else [c for c in cases if c["id"] in set(args.case)]
    if not selected:
        parser.error("choose --list, --case ID, or --all")
    if not docker_available():
        print("Docker is not available; installation tests were not run.", file=sys.stderr)
        return 2
    if not args.yes:
        print("Refusing to run without --yes. Containers are isolated but still download code.", file=sys.stderr)
        return 2

    results = [run_case(case) for case in selected]
    if RESULTS_JSON.exists():
        try:
            previous = {item["id"]: item for item in json.loads(RESULTS_JSON.read_text(encoding="utf-8")).get("cases", [])}
            for item in results:
                previous[item["id"]] = item
            order = {case["id"]: index for index, case in enumerate(cases)}
            results = sorted(previous.values(), key=lambda item: order.get(item["id"], 999))
        except (json.JSONDecodeError, KeyError):
            pass
    write_results(results)
    for item in results:
        print(f"{item['status']:8} {item['id']} ({item['duration_seconds']}s)")
    return 0 if all(item["status"] == "PASS" for item in results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
